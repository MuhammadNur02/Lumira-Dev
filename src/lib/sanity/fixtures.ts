let variantSeq = 100000
function licenses(prices: [number, number, number]): License[] {
  const lsProductId = 50000 + Math.floor(variantSeq / 10)
  return (['personal', 'team', 'extended'] as const).map((tier, i) => ({
    tier,
    lsProductId,
    lsVariantId: ++variantSeq,
    priceCents: prices[i]!,
    activationLimit: [1, 5, 25][i]!,
    rights: RIGHTS[tier],
    buyUrl: null,
  }))
}

