// ---------- Assemble ----------
function toCard(seed: Seed, rel: ChangelogEntry[]): ProductCard {
  const own = rel.filter((r) => r.product.slug === seed.slug && r.status === 'published')
  const latest = own[0]
  return {
    _id: `product-${seed.slug}`,
    name: seed.name,
    slug: seed.slug,
    line: seed.line,
    templateType: seed.templateType ?? null,
    tagline: seed.tagline,
    hero: art(seed.slug, `${seed.name} interface preview`),
    video: null,
    stack: seed.stack,
    capabilities: seed.capabilities,
    priceFromCents: Math.min(...seed.prices),
    inAllAccess: true,
    popularity: seed.popularity,
    createdAt: seed.createdAt,
    latestRelease: latest
      ? {
          version: latest.version,
          type: latest.type,
          title: latest.title,
          releasedAt: latest.releasedAt,
          compatibility: latest.compatibility,
        }
      : null,
  }
}

